- 每层通关后；
- 天关内战败结算时；
- 北丑处结束游戏前；
- 打开「天关记录」时。

排行榜按最高层数降序排列；同层时先达成者排名靠前。一个账号只保留一条记录，层数只升不降，主角名称会随最近一次上报刷新。天关层数没有上限。

